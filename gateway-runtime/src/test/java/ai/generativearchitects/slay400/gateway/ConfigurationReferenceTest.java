package ai.generativearchitects.slay400.gateway;

import static org.assertj.core.api.Assertions.assertThat;

import ai.generativearchitects.slay400.gateway.config.ConfigurationKeys;
import ai.generativearchitects.slay400.gateway.config.ConfigurationKeys.Key;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

/**
 * The configuration reference of the documentation (specs/documentation.md section 7, gateway kickoff 09), generated from
 * {@link ConfigurationKeys} and the hand-written notes of {@code docs/reference/_notes/configuration/}. This test fails when the
 * committed page is not what the catalogue and the notes give; with {@code -Dslay400.docs.write=true} it writes the page instead.
 */
class ConfigurationReferenceTest {

    static final Path DOCS = Path.of("..", "docs");
    static final Path PAGE = DOCS.resolve("reference/configuration/index.md");
    static final Path NOTES = DOCS.resolve("reference/_notes/configuration");
    static final String EXAMPLE = "examples/reference/config.yaml";
    static final String COMMAND = "./mvnw -pl gateway-runtime test -Dtest=ConfigurationReferenceTest -Dslay400.docs.write=true";

    @Test
    void thePageIsWhatTheCatalogueAndTheNotesGive() throws IOException {
        String page = render();
        if (Boolean.getBoolean("slay400.docs.write")) {
            Files.createDirectories(PAGE.getParent());
            Files.writeString(PAGE, page);
        }
        assertThat(Files.readString(PAGE)).as("docs/reference/configuration/index.md is stale; regenerate with: " + COMMAND).isEqualTo(page);
    }

    @Test
    void everyKeyIsInOneGroupOfThePage() {
        int listed = groups().values().stream().mapToInt(List::size).sum();
        assertThat(listed).isEqualTo(ConfigurationKeys.KEYS.size());
    }

    /** The keys by heading of the page, in the order of the catalogue. */
    static Map<String, List<Key>> groups() {
        Map<String, List<Key>> groups = new LinkedHashMap<>();
        for (String heading : List.of("server", "management", "reload", "tenants", "environments")) {
            groups.put(heading, new ArrayList<>());
        }
        for (Key key : ConfigurationKeys.KEYS) {
            String heading = key.path().startsWith(ConfigurationKeys.ENVIRONMENT_PATH + ".") ? "environments" : key.path().split("\\.")[0];
            groups.get(heading).add(key);
        }
        return groups;
    }

    static String render() throws IOException {
        StringBuilder out = new StringBuilder();
        out.append("""
                ---
                title: Configuration reference
                description: Every key of the gateway's configuration file, its type, default and limits, with a complete example.
                section: reference
                slug: configuration
                order: 30
                appliesTo: "0.1"
                ---

                """);
        out.append("<!-- Generated by ConfigurationReferenceTest from ConfigurationKeys of gateway-runtime and docs/reference/_notes/configuration/. ")
                .append("Do not edit by hand; regenerate with: ").append(COMMAND).append(" -->\n\n");
        out.append("# Configuration reference\n\n");
        out.append(note("intro")).append('\n');
        for (Map.Entry<String, List<Key>> group : groups().entrySet()) {
            out.append("## ").append(group.getKey()).append("\n\n");
            out.append(note(group.getKey())).append('\n');
            out.append("| Key | Type | Required | Default | Limits | A change takes effect | Meaning |\n");
            out.append("|---|---|---|---|---|---|---|\n");
            for (Key key : group.getValue()) {
                out.append("| ").append(code(key.path())).append(" | ").append(cell(key.type())).append(" | ").append(cell(key.required()))
                        .append(" | ").append(key.byDefault().isEmpty() ? "" : code(key.byDefault())).append(" | ").append(cell(key.limits()))
                        .append(" | ").append(cell(key.takesEffect())).append(" | ").append(cell(key.meaning())).append(" |\n");
            }
            out.append('\n');
        }
        out.append("## Complete example\n\n");
        out.append("Every key, with a `mock` and an `ibmi` environment. The gateway starts with it, as a test of this repository checks, once ")
                .append("`bundles/` holds a bundle, `tls/` holds the certificate and its encrypted key, and the environment variables are set.\n\n");
        out.append("<!-- snippet: ").append(EXAMPLE).append(" -->\n```yaml\n")
                .append(Files.readString(DOCS.resolve(EXAMPLE)).stripTrailing()).append("\n```\n");
        return out.toString();
    }

    private static String note(String name) throws IOException {
        Path file = NOTES.resolve(name + ".md");
        return Files.readString(file).stripTrailing() + "\n";
    }

    private static String code(String text) {
        return "`" + text.replace("|", "\\|") + "`";
    }

    private static String cell(String text) {
        return text.replace("|", "\\|");
    }
}
